function selectedAgents({ agents, home, scope }) {
  const pool = [...AGENTS, STANDARD];
  if (agents === "all") return pool;
  const wanted = new Set(agents.split(",").map((s) => s.trim()).filter(Boolean));
  const detected = detectHomeAgents(home);
  return pool.filter((a) => wanted.has(a.id) || (wanted.size === 0 && (detected.has(a.id) || a.id === STANDARD.id)));
}

function printList(agents, { home, scope }) {
  const detected = detectHomeAgents(home);
  console.log("zoom-out surfaces\n");
  for (const a of [...AGENTS, STANDARD]) {
    const state = agents.includes(a) ? "selected" : detected.has(a.id) ? "available" : "-";
    const skills = [...(a.skills?.user ?? []), ...(a.skills?.project ?? [])];
    console.log(`${a.id.padEnd(16)} ${a.share.padEnd(5)} ${state.padEnd(10)} ${a.injection}`);
    for (const s of skills) console.log(`${" ".repeat(16)} skill  ${s}/${SKILL_NAME}/`);
    for (const r of a.rules ?? []) console.log(`${" ".repeat(16)} rule   ${r.scope}: ${r.path}`);
  }
  console.log("\n--agents all | --agents <id,...> to widen; --scope user|project|all");
}

function printMatrix() {
  const rows = [
    "| Agent | At-work share | Skill discovery root | Always-on surface |",
    "| --- | --- | --- | --- |",
  ];
  for (const a of [...AGENTS, STANDARD]) {
    const roots = [...(a.skills?.user ?? []), ...(a.skills?.project ?? [])];
    const rules = (a.rules ?? []).map((r) => r.path).join(", ") || a.injection;
    rows.push(
      `| ${a.label} | ${a.share} | ${roots.length ? roots.map((r) => `${r}/zoom-out/`).join(", ") : "—"} | ${rules} |`
    );
  }
  console.log(rows.join("\n"));
}

