// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

function reflexBlock(indent) {
  return REFLEX.split("\n")
    .map((line) => (indent && line ? indent + line : line))
    .join("\n");
}

// Body of an always-on rule: the reflex verbatim, plus where to find the full
// protocol. Generated, never hand-edited.
function rulesBody() {
  return `${reflexBlock("")}

${SKILL_POINTER}`;
}

function frontmatterYaml(meta) {
  const lines = [GENERATED_YAML];
  for (const [key, value] of Object.entries(meta || {})) {
    lines.push(`${key}: ${JSON.stringify(value)}`);
  }
  return lines.join("\n");
}

function renderRuleFile(entry) {
  const header = entry.frontmatter
    ? `---\n${frontmatterYaml(entry.frontmatter)}\n---\n\n`
    : "";
  return `${header}${GENERATED}\n\n${rulesBody()}\n`;
}

// A file belongs to this installer only if it carries the generated marker.
// Everything else is someone's hand-written rule and is left alone.
function isGenerated(content) {
  return (
    content.startsWith(`---\n${GENERATED_YAML}`) || content.startsWith(GENERATED)
  );
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Append or replace the managed block inside a shared file (AGENTS.md,
// GEMINI.md, ...). Everything outside the markers is preserved.
function upsertBlock(existing, body) {
  const block = `${BEGIN}\n${body}\n${END}`;
  const pattern = new RegExp(`${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}`);
  if (pattern.test(existing)) return existing.replace(pattern, block);
  const trimmed = existing.trimEnd();
  return trimmed === "" ? `${block}\n` : `${trimmed}\n\n${block}\n`;
}

function stripBlock(existing) {
  const pattern = new RegExp(`\\n*${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}\\n*`);
  return pattern.test(existing) ? existing.replace(pattern, "\n") : null;
}

// ---------------------------------------------------------------------------
// Paths and planning
// ---------------------------------------------------------------------------

function expand(path, { home, root, scope }) {
  if (path.startsWith("~/")) return join(home, path.slice(2));
  return join(scope === "user" ? home : root, path);
}

function planFor(agent, { scopes, home, root }) {
  const plan = [];
  for (const scope of scopes) {
    const roots = agent.skills?.[scope] ?? [];
    for (const raw of new Set(roots)) {
      const dest = join(expand(raw, { home, root, scope }), SKILL_NAME);
      plan.push({ kind: "skill", agent, scope, raw, dest });
    }
    for (const rule of (agent.rules || []).filter((r) => r.scope === scope)) {
      const dest = expand(rule.path, { home, root, scope });
      plan.push({ kind: "rule", agent, scope, rule, raw: rule.path, dest });
    }
  }
  return plan;
}

function detectHomeAgents(home) {
  const detected = new Set();
  for (const agent of AGENTS) {
    if (!agent.detect) continue;
    if (agent.detect.some((d) => existsSync(join(home, d.replace(/^~\//, ""))))) {
      detected.add(agent.id);
    }
  }
  return detected;
}

// ---------------------------------------------------------------------------
// Apply
// ---------------------------------------------------------------------------

function installItem(item, ctx) {
  return item.kind === "skill" ? installSkill(item, ctx) : installRule(item, ctx);
}

function installSkill(item, ctx) {
  const { dryRun } = ctx;
  if (dryRun)
    return [`skill  ${item.raw.replace(/\/$/, "")}/${SKILL_NAME}/  <- skills/${SKILL_NAME}/`];
  mkdirSync(dirname(item.dest), { recursive: true });
  cpSync(SKILL_SRC, item.dest, { recursive: true });
  return [`skill  ${item.dest}`];
}

function installRule(item, ctx) {
  const { dryRun, force } = ctx;
  if (item.rule.kind === "file") {
    if (existsSync(item.dest) && !force) {
      const current = readFileSync(item.dest, "utf8");
      if (!isGenerated(current)) {
        return [`SKIP   ${item.dest} (exists, not generated; --force to overwrite)`];
      }
    }
    if (dryRun) return [`rule   ${item.rule.path}`];
    mkdirSync(dirname(item.dest), { recursive: true });
    writeFileSync(item.dest, renderRuleFile(item.rule));
    return [`rule   ${item.dest}`];
  }
  const existing = existsSync(item.dest) ? readFileSync(item.dest, "utf8") : "";
  if (dryRun) return [`rule   ${item.raw} (managed block)`];
  mkdirSync(dirname(item.dest), { recursive: true });
  writeFileSync(item.dest, upsertBlock(existing, rulesBody()));
  return [`rule   ${item.dest} (managed block)`];
}

function uninstallItem(item, ctx) {
  const { dryRun } = ctx;
  if (!existsSync(item.dest)) return [];
  if (item.kind === "skill") {
    if (dryRun) return [`skill  -${item.dest}`];
    rmSync(item.dest, { recursive: true, force: true });
    return [`skill  -${item.dest}`];
  }
  if (item.rule.kind === "file") {
    const current = readFileSync(item.dest, "utf8");
    if (!isGenerated(current)) {
      return [`SKIP   ${item.dest} (not generated; left alone)`];
    }
    if (dryRun) return [`rule   -${item.dest}`];
    rmSync(item.dest);
    return [`rule   -${item.dest}`];
  }
  const stripped = stripBlock(readFileSync(item.dest, "utf8"));
  if (stripped === null) return [];
  // A file that held nothing but the managed block was created by this
  // installer; leaving an empty file behind would be litter, not safety.
  if (stripped.trim() === "") {
    if (dryRun) return [`rule   -${item.raw} (file emptied, removed)`];
    rmSync(item.dest);
    return [`rule   -${item.dest} (file emptied, removed)`];
  }
  if (dryRun) return [`rule   -${item.raw} (managed block)`];
  writeFileSync(item.dest, stripped.replace(/^\n+/, ""));
  return [`rule   -${item.dest} (managed block)`];
}

