#!/usr/bin/env node
// zoom-out installer.
//
// One source of truth — hooks/reflex.txt (the reflex) and skills/zoom-out/
// (the full protocol) — rendered into each coding agent's documented discovery
// surface. Nothing here is hand-maintained per agent: adding an agent is a row
// in AGENTS, not new code, so the surface set cannot silently drift away from
// the skill.
//
// Two kinds of surface, because agents differ in what they guarantee:
//
//   skill  — a SKILL.md directory the agent discovers and loads on relevance.
//            Portable across the Agent Skills standard (agentskills.io), but
//            trigger-dependent: the agent must decide the skill is relevant.
//   rules  — an always-on instruction file the agent injects into every
//            session regardless of triggering. This is where the reflex is
//            guaranteed rather than hoped for, on agents with no hook API.
//
// Usage:
//   node scripts/install.mjs [options]
//
//   --scope user|project|all   Which scopes to install (default: all)
//   --agents <ids|all>         Comma-separated agent ids, or all (default:
//                              detected agents plus the portable standard)
//   --home <dir>               Home directory to install into (default: $HOME)
//   --root <dir>               Project root (default: cwd)
//   --list                     Show the surface matrix and exit
//   --matrix                   Print the README compatibility matrix and exit
//   --dry-run                  Print planned writes without touching disk
//   --uninstall                Remove what this script installed
//   --force                    Overwrite unmanaged rule files
