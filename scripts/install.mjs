function parseArgs(argv) {
  const opts = {
    scope: "all",
    agents: "",
    home: homedir(),
    root: process.cwd(),
    dryRun: false,
    force: false,
    uninstall: false,
    list: false,
    matrix: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const next = () => {
      const value = argv[++i];
      if (value === undefined) throw new Error(`${arg} needs a value`);
      return value;
    };
    switch (arg) {
      case "--scope": opts.scope = next(); break;
      case "--agents": opts.agents = next(); break;
      case "--home": opts.home = resolve(next()); break;
      case "--root": opts.root = resolve(next()); break;
      case "--dry-run": opts.dryRun = true; break;
      case "--force": opts.force = true; break;
      case "--uninstall": opts.uninstall = true; break;
      case "--list": opts.list = true; break;
      case "--matrix": opts.matrix = true; break;
      case "-h":
      case "--help": opts.help = true; break;
      default: throw new Error(`unknown option ${arg}`);
    }
  }
  return opts;
}

function main(argv) {
  const opts = parseArgs(argv);
  if (opts.help) {
    console.log(readFileSync(new URL(import.meta.url), "utf8").split("\n").slice(1, 30).map((l) => l.replace(/^\/\/ ?/, "")).join("\n"));
    return 0;
  }
  if (opts.matrix) {
    printMatrix();
    return 0;
  }
  const scopes = opts.scope === "all" ? ["user", "project"] : [opts.scope];
  if (!scopes.every((s) => s === "user" || s === "project")) {
    throw new Error(`--scope must be user, project, or all (got ${opts.scope})`);
  }
  const agents = selectedAgents({ agents: opts.agents, home: opts.home, scope: scopes });
  if (opts.list) {
    printList(agents, { home: opts.home, scope: scopes });
    return 0;
  }

  // Several agents share a surface (AGENTS.md, ~/.agents/skills); write each
  // destination once, whatever the number of agents that read it.
  const seen = new Set();
  const items = agents
    .flatMap((a) => planFor(a, { scopes, home: opts.home, root: opts.root }))
    .filter((item) => {
      const key = `${item.kind}:${item.dest}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
  const ctx = { ...opts };
  const verb = opts.uninstall ? "uninstall" : "install";
  console.log(
    `zoom-out ${verb}${opts.dryRun ? " (dry run)" : ""} — ${items.length} surface(s), ` +
      `home=${opts.home} root=${opts.root}`
  );
  if (items.length === 0) {
    console.log("nothing selected; use --agents all");
    return 0;
  }
  for (const item of items) {
    const lines = opts.uninstall ? uninstallItem(item, ctx) : installItem(item, ctx);
    for (const line of lines) console.log("  " + line);
  }
  if (!opts.dryRun) {
    console.log(
      opts.uninstall
        ? "\nRemoved. Restart any running agent session to pick up the change."
        : "\nDone. Restart any running agent session so it re-reads its instruction files."
    );
  }
  return 0;
}

